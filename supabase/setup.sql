-- ===== 1. Website settings (all editable content) =====
create table if not exists public.site_settings (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;

drop policy if exists "Public can read settings" on public.site_settings;
create policy "Public can read settings" on public.site_settings
  for select to anon, authenticated using (true);

drop policy if exists "Admin can write settings" on public.site_settings;
create policy "Admin can write settings" on public.site_settings
  for all to authenticated
  using ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com')
  with check ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com');

-- ===== 2. Contact form messages =====
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  service text,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.contact_messages add column if not exists is_read boolean not null default false;
alter table public.contact_messages enable row level security;

drop policy if exists "Allow anonymous inserts" on public.contact_messages;
create policy "Allow anonymous inserts" on public.contact_messages
  for insert to anon, authenticated with check (true);

drop policy if exists "Admin can read messages" on public.contact_messages;
create policy "Admin can read messages" on public.contact_messages
  for select to authenticated using ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com');

drop policy if exists "Admin can update messages" on public.contact_messages;
create policy "Admin can update messages" on public.contact_messages
  for update to authenticated using ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com');

drop policy if exists "Admin can delete messages" on public.contact_messages;
create policy "Admin can delete messages" on public.contact_messages
  for delete to authenticated using ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com');

-- ===== 3. Social media tokens (PRIVATE — admin only, never public) =====

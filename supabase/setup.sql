alter table public.social_secrets enable row level security;

drop policy if exists "Admin manages social secrets" on public.social_secrets;
create policy "Admin manages social secrets" on public.social_secrets
  for all to authenticated
  using ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com')
  with check ((auth.jwt() ->> 'email') = 'fareedulhassan0@gmail.com');

-- ===== 4. Social feed cache (used only by the social-feed function) =====
create table if not exists public.social_cache (
  platform text primary key,
  source text,
  data jsonb not null default '[]'::jsonb,
